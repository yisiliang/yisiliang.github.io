def wording(text):
    for old,new in REPLACEMENTS.items():text=text.replace(old,new)
    return text

def html_wording(source):
    # Preserve byte-exact upstream snippets and stylesheet/script content.
    protected=re.compile(r'<(pre|code|script|style)\b[^>]*>.*?</\1>',re.S|re.I)
    parts=[];end=0
    for match in protected.finditer(source):
        parts.extend([wording(source[end:match.start()]),match.group()]);end=match.end()
    parts.append(wording(source[end:]));return ''.join(parts)

def markdown_wording(source):
    parts=re.split(r'(```[^\n]*\n.*?\n```)',source,flags=re.S)
    return ''.join(part if i%2 else wording(part) for i,part in enumerate(parts))
